/**
 * Каталог паспортов ключевых метрик (Отчёт приёмки §10.9, ACC-033/034).
 *
 * Паспорт обязателен для каждой метрики на главных дашбордах: название,
 * управленческий вопрос, формула, числитель/знаменатель, единица, источник,
 * период, уровень агрегации, исключения, поведение при неполных данных,
 * путь детализации и статус значения. Происхождение каждого значения
 * хранится здесь (служебный паспорт набора), пользователю не показывается.
 */

export interface MetricPassport {
  /** Код метрики (стабильный ключ). */
  code: string
  /** Название в интерфейсе. */
  name: string
  /** Управленческий вопрос роли. */
  question: string
  /** Роли-потребители. */
  roles: string[]
  /** Формула (человекочитаемая). */
  formula: string
  /** Числитель. */
  numerator: string
  /** Знаменатель. */
  denominator: string
  /** Единица измерения. */
  unit: string
  /** Источник данных. */
  source: string
  /** Период набора. */
  period: string
  /** Частота обновления. */
  frequency: string
  /** Уровень агрегации. */
  aggregation: string
  /** Исключения из расчёта. */
  exclusions: string
  /** Поведение при неполных данных. */
  incomplete: string
  /** Путь детализации до первичных записей. */
  drilldown: string
  /** Статус значения. */
  status: 'подтверждено' | 'рассчитано' | 'внутреннее допущение'
}

